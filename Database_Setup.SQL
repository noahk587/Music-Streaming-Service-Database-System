
PRAGMA foreign_keys = ON;

CREATE TABLE Device (
    device_id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT
);


CREATE TABLE User (
    user_id INTEGER PRIMARY KEY,
    name TEXT,
    username TEXT,
    email TEXT,
    password_hash TEXT,
    created_at TEXT,
    modified_at TEXT
);


CREATE TABLE SubscriptionPlan (
    subscription_id INTEGER PRIMARY KEY,
    type TEXT,
    price REAL,
    duration_months INTEGER
);


CREATE TABLE UserSubscription (
    user_subscription_id INTEGER PRIMARY KEY,
    subscription_id INTEGER,
    user_id INTEGER,
    start_date TEXT,
    end_date TEXT,
    FOREIGN KEY (user_id) REFERENCES User(user_id),
    FOREIGN KEY (subscription_id) REFERENCES SubscriptionPlan(subscription_id)
);

CREATE TABLE Region (
    region_id INTEGER PRIMARY KEY,
    region TEXT
);


CREATE TABLE UserRegion (
    user_region_id INTEGER PRIMARY KEY,
    user_id INTEGER,
    region_id INTEGER,
    FOREIGN KEY (user_id) REFERENCES User(user_id),
    FOREIGN KEY (region_id) REFERENCES Region(region_id)
);



CREATE TABLE UserDevice (
    user_device_id INTEGER PRIMARY KEY,
    user_id INTEGER NOT NULL,
    device_id INTEGER NOT NULL,
    FOREIGN KEY (user_id) REFERENCES User(user_id),
    FOREIGN KEY (device_id) REFERENCES Device(device_id)
);

CREATE TABLE Genre (
    genre_id INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE Artist (
    artist_id INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE Album (
    album_id INTEGER PRIMARY KEY,
    artist_id INTEGER,
    title TEXT,
    release_date INTEGER,
    FOREIGN KEY (artist_id) REFERENCES Artist(artist_id)
);


CREATE TABLE Song (
    song_id INTEGER PRIMARY KEY,
    album_id INTEGER,
    title TEXT,
    duration TEXT,
    FOREIGN KEY (album_id) REFERENCES Album(album_id)
);

CREATE TABLE SongGenre (
    song_genre_id INTEGER PRIMARY KEY,
    song_id INTEGER NOT NULL,
    genre_id INTEGER NOT NULL,
    FOREIGN KEY (song_id) REFERENCES Song(song_id),
    FOREIGN KEY (genre_id) REFERENCES Genre(genre_id)
);

CREATE TABLE Playlist (
    playlist_id INTEGER PRIMARY KEY,
    user_id INTEGER NOT NULL,
    name TEXT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES User(user_id)
);

CREATE TABLE UserPlaylist (
    user_playlist_id INTEGER PRIMARY KEY,
    user_id INTEGER NOT NULL,
    playlist_id INTEGER NOT NULL,
    FOREIGN KEY (user_id) REFERENCES User(user_id),
    FOREIGN KEY (playlist_id) REFERENCES Playlist(playlist_id)
);

CREATE TABLE PlaylistSong (
    playlist_song_id INTEGER PRIMARY KEY,
    playlist_id INTEGER NOT NULL,
    song_id INTEGER NOT NULL,
    FOREIGN KEY (playlist_id) REFERENCES Playlist(playlist_id),
    FOREIGN KEY (song_id) REFERENCES Song(song_id)
);


